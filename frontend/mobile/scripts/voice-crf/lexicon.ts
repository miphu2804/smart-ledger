const SIZES = ['lon', 'chai', 'gói', 'hộp', 'túi 1kg', '500ml', '1 lít', 'size M', 'size L', 'loại 1', 'loại lớn', 'vị cay', 'vị ngọt'];

/**
 * Danh mục ~`n` món để đo độ trễ: catalog eval của shop đầu tiên + các món train nhân biến thể quy cách.
 * Tất định (không ngẫu nhiên) để mỗi lần đo cùng một dữ liệu.
 */
export function bigCatalog(base: ParseableProduct[], n: number): ParseableProduct[] {
  const out: ParseableProduct[] = [...base];
  const pool = Object.values(TRAIN_CATALOGS).flat();
  let id = 50_000;
  for (let round = 0; out.length < n; round++) {
    for (const p of pool) {
      if (out.length >= n) break;
      const name = round === 0 ? p.name : `${p.name} ${SIZES[(round + p.name.length) % SIZES.length]}${round > SIZES.length ? ` ${round}` : ''}`;
      out.push({ id: id++, name, price: p.price });
    }
  }
  return out;
}
