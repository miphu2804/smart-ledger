from evaluation.core.schema import Case, MetricResult, Output
from evaluation.metrics.judge import Judge


class ResponseQualityEvaluator:
    layer = "response_quality"

    def __init__(self, judge: Judge) -> None:
        self.judge = judge

    async def evaluate(self, case: Case, output: Output) -> list[MetricResult]:
        rated = await self.judge.rate_metric(
            self.layer, "answer_faithfulness", self._prompt(output), case, output
        )
        return [rated] if rated else []

    @staticmethod
    def _prompt(output: Output) -> str:
        """Answer Faithfulness, against the tool results and the recalled memories."""
        values = output.values
        context = [call["result"] for call in values["tool_calls"]]
        context += [memory["content"] for memory in values["memories"]]
        return f"""[Criteria]
The answer generated by the AI assistant should be faithful to the provided
context and should not include information that isn't supported by the context.

[The Start of Provided Context]
{chr(10).join(context) or "(none)"}
[The End of Provided Context]

[The Start of AI Assistant's Answer]
{values["answer"]}
[The End of AI Assistant's Answer]"""
