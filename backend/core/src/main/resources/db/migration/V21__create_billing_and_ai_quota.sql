-- Owner-approved phase-two schema, 2026-11-07. No payment, subscription or chat writer is enabled.
-- Additive and forward-only: retain committed evidence on application rollback.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE billing_payment_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    integration_key VARCHAR(64) NOT NULL CHECK (integration_key ~ '^[A-Za-z0-9_-]+$'),
    plan_code VARCHAR(32) NOT NULL,
    plan_version INTEGER NOT NULL CHECK (plan_version > 0),
    duration_months INTEGER NOT NULL,
    quota_policy_version INTEGER NOT NULL CHECK (quota_policy_version > 0),
    amount_vnd BIGINT NOT NULL CHECK (amount_vnd > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'VND'),
    recipient_bank_code VARCHAR(32) NOT NULL CHECK (btrim(recipient_bank_code) <> ''),
    recipient_account_number VARCHAR(64) NOT NULL CHECK (btrim(recipient_account_number) <> ''),
    recipient_account_name VARCHAR(255) NOT NULL CHECK (btrim(recipient_account_name) <> ''),
    payment_code VARCHAR(15) NOT NULL CHECK (payment_code ~ '^SLP[A-Z0-9]{12}$'),
    idempotency_key VARCHAR(255) NOT NULL CHECK (idempotency_key <> '' AND idempotency_key = btrim(idempotency_key)),
    request_hash VARCHAR(64) NOT NULL CHECK (request_hash ~ '^[a-f0-9]{64}$'),
    hash_version INTEGER NOT NULL CHECK (hash_version > 0),
    original_response JSONB NOT NULL CHECK (jsonb_typeof(original_response) = 'object'),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'EXPIRED', 'PAID')),
    fulfillment_status VARCHAR(16) NOT NULL DEFAULT 'NOT_STARTED'
        CHECK (fulfillment_status IN ('NOT_STARTED', 'PENDING', 'APPLIED')),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    fulfilled_grant_id BIGINT,
    CONSTRAINT ck_billing_request_term CHECK (
        (plan_code = 'FULL_MONTHLY' AND duration_months = 1)
        OR (plan_code = 'FULL_QUARTERLY' AND duration_months = 3)),
    CONSTRAINT ck_billing_request_expiry CHECK (expires_at = created_at + INTERVAL '30 minutes'),
    CONSTRAINT ck_billing_request_paid CHECK (
        (status = 'PAID') = (paid_at IS NOT NULL) AND (paid_at IS NULL OR paid_at >= created_at)),
    CONSTRAINT ck_billing_request_fulfillment CHECK (
        (status <> 'PAID' AND fulfillment_status = 'NOT_STARTED')
        OR (status = 'PAID' AND fulfillment_status IN ('PENDING', 'APPLIED'))),
    CONSTRAINT ck_billing_request_grant CHECK ((fulfillment_status = 'APPLIED') = (fulfilled_grant_id IS NOT NULL)),
    CONSTRAINT uq_billing_request_code UNIQUE (integration_key, payment_code),
    CONSTRAINT uq_billing_request_key UNIQUE (payer_user_id, idempotency_key),
    CONSTRAINT uq_billing_request_scope UNIQUE (id, payer_user_id, integration_key)
);
CREATE INDEX idx_billing_requests_owner ON billing_payment_requests(payer_user_id, created_at DESC, id DESC);
CREATE INDEX idx_billing_requests_pending_grant ON billing_payment_requests(paid_at, id)
    WHERE status = 'PAID' AND fulfillment_status = 'PENDING';

CREATE TABLE billing_bank_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    integration_key VARCHAR(64) NOT NULL CHECK (integration_key ~ '^[A-Za-z0-9_-]+$'),
    provider_transaction_id VARCHAR(64) NOT NULL CHECK (provider_transaction_id ~ '^[1-9][0-9]*$'),
    first_received_at TIMESTAMPTZ NOT NULL,
    bank_occurred_at TIMESTAMPTZ,
    direction VARCHAR(3) NOT NULL CHECK (direction IN ('IN', 'OUT')),
    amount_vnd BIGINT NOT NULL CHECK (amount_vnd > 0),
    bank_code VARCHAR(32) NOT NULL CHECK (btrim(bank_code) <> ''),
    account_number VARCHAR(64) NOT NULL CHECK (btrim(account_number) <> ''),
    sub_account VARCHAR(64) CHECK (sub_account IS NULL OR btrim(sub_account) <> ''),
    payment_code VARCHAR(15) CHECK (payment_code IS NULL OR payment_code ~ '^SLP[A-Z0-9]{12}$'),
    matched_request_id BIGINT,
    payer_user_id BIGINT,
    disposition VARCHAR(32) NOT NULL CHECK (disposition IN ('ACCEPTED', 'REVIEW_REQUIRED', 'IGNORED_OUTGOING')),
    reason VARCHAR(40) NOT NULL CHECK (reason IN ('MATCHED', 'LATE_RECEIPT', 'AMOUNT_MISMATCH',
        'RECIPIENT_MISMATCH', 'MISSING_CODE', 'UNKNOWN_CODE', 'AMBIGUOUS_CODE', 'EXTRA_TRANSFER', 'OUTGOING')),
    financial_hash VARCHAR(64) NOT NULL CHECK (financial_hash ~ '^[a-f0-9]{64}$'),
    hash_version INTEGER NOT NULL CHECK (hash_version > 0),
    CONSTRAINT ck_billing_bank_link CHECK ((matched_request_id IS NULL) = (payer_user_id IS NULL)),
    CONSTRAINT ck_billing_bank_outcome CHECK (
        (disposition = 'ACCEPTED' AND direction = 'IN' AND matched_request_id IS NOT NULL AND reason = 'MATCHED')
        OR (disposition = 'REVIEW_REQUIRED' AND direction = 'IN' AND reason NOT IN ('MATCHED', 'OUTGOING'))
        OR (disposition = 'IGNORED_OUTGOING' AND direction = 'OUT' AND reason = 'OUTGOING')),
    CONSTRAINT fk_billing_bank_request FOREIGN KEY (matched_request_id, payer_user_id, integration_key)
        REFERENCES billing_payment_requests(id, payer_user_id, integration_key) ON DELETE RESTRICT,
    CONSTRAINT uq_billing_bank_provider UNIQUE (integration_key, provider_transaction_id),
    CONSTRAINT uq_billing_bank_scope UNIQUE (id, matched_request_id, payer_user_id, integration_key, disposition)
);
CREATE UNIQUE INDEX uq_billing_bank_accepted ON billing_bank_transactions(matched_request_id) WHERE disposition = 'ACCEPTED';
CREATE INDEX idx_billing_bank_request ON billing_bank_transactions(matched_request_id, first_received_at, id);
CREATE INDEX idx_billing_bank_review ON billing_bank_transactions(first_received_at, id) WHERE disposition = 'REVIEW_REQUIRED';

CREATE TABLE billing_subscription_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    activated_at TIMESTAMPTZ NOT NULL,
    purchased_months INTEGER NOT NULL CHECK (purchased_months > 0),
    quota_policy_version INTEGER NOT NULL CHECK (quota_policy_version > 0),
    expires_at TIMESTAMPTZ NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT true,
    version BIGINT NOT NULL CHECK (version > 0),
    CONSTRAINT ck_billing_period_dates CHECK (expires_at > activated_at),
    CONSTRAINT uq_billing_period_scope UNIQUE (id, user_id)
);
CREATE UNIQUE INDEX uq_billing_period_current ON billing_subscription_periods(user_id) WHERE is_current;
CREATE INDEX idx_billing_period_owner ON billing_subscription_periods(user_id, activated_at DESC, id DESC);

CREATE TABLE billing_subscription_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_request_id BIGINT NOT NULL UNIQUE,
    accepted_transaction_id BIGINT NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    integration_key VARCHAR(64) NOT NULL,
    accepted_disposition VARCHAR(32) NOT NULL DEFAULT 'ACCEPTED' CHECK (accepted_disposition = 'ACCEPTED'),
    period_id BIGINT NOT NULL,
    period_version BIGINT NOT NULL CHECK (period_version > 0),
    duration_months INTEGER NOT NULL CHECK (duration_months IN (1, 3)),
    previous_expires_at TIMESTAMPTZ,
    resulting_expires_at TIMESTAMPTZ NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_billing_grant_dates CHECK (resulting_expires_at > applied_at
        AND (previous_expires_at IS NULL OR resulting_expires_at > previous_expires_at)),
    CONSTRAINT fk_billing_grant_request FOREIGN KEY (payment_request_id, user_id, integration_key)
        REFERENCES billing_payment_requests(id, payer_user_id, integration_key) ON DELETE RESTRICT,
    CONSTRAINT fk_billing_grant_accepted FOREIGN KEY (
        accepted_transaction_id, payment_request_id, user_id, integration_key, accepted_disposition)
        REFERENCES billing_bank_transactions(id, matched_request_id, payer_user_id, integration_key, disposition) ON DELETE RESTRICT,
    CONSTRAINT fk_billing_grant_period FOREIGN KEY (period_id, user_id)
        REFERENCES billing_subscription_periods(id, user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_billing_grant_scope UNIQUE (id, payment_request_id, user_id),
    CONSTRAINT uq_billing_grant_version UNIQUE (period_id, period_version)
);
CREATE INDEX idx_billing_grants_owner ON billing_subscription_grants(user_id, applied_at DESC, id DESC);
ALTER TABLE billing_payment_requests ADD CONSTRAINT fk_billing_request_grant
    FOREIGN KEY (fulfilled_grant_id, id, payer_user_id)
    REFERENCES billing_subscription_grants(id, payment_request_id, user_id) ON DELETE RESTRICT;

CREATE TABLE ai_quota_windows (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('FREE_DAILY', 'PAID_WEEKLY')),
    period_id BIGINT,
    policy_version INTEGER NOT NULL CHECK (policy_version > 0),
    window_start TIMESTAMPTZ NOT NULL,
    nominal_end TIMESTAMPTZ NOT NULL,
    limit_count INTEGER NOT NULL CHECK (limit_count > 0),
    committed_count INTEGER NOT NULL DEFAULT 0 CHECK (committed_count >= 0),
    reserved_count INTEGER NOT NULL DEFAULT 0 CHECK (reserved_count >= 0),
    CONSTRAINT ck_ai_quota_scope CHECK ((kind = 'FREE_DAILY' AND period_id IS NULL)
        OR (kind = 'PAID_WEEKLY' AND period_id IS NOT NULL)),
    CONSTRAINT ck_ai_quota_dates CHECK (nominal_end > window_start),
    CONSTRAINT ck_ai_quota_capacity CHECK (committed_count::BIGINT + reserved_count::BIGINT <= limit_count),
    CONSTRAINT fk_ai_quota_period FOREIGN KEY (period_id, user_id)
        REFERENCES billing_subscription_periods(id, user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_ai_quota_scope UNIQUE (id, user_id)
);
CREATE UNIQUE INDEX uq_ai_quota_free ON ai_quota_windows(user_id, window_start) WHERE kind = 'FREE_DAILY';
CREATE UNIQUE INDEX uq_ai_quota_paid ON ai_quota_windows(user_id, period_id, window_start) WHERE kind = 'PAID_WEEKLY';
CREATE INDEX idx_ai_quota_period ON ai_quota_windows(period_id, user_id);

CREATE TABLE ai_turn_usages (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    shop_id BIGINT NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    operation VARCHAR(16) NOT NULL DEFAULT 'CHAT' CHECK (operation = 'CHAT'),
    idempotency_key VARCHAR(255) NOT NULL CHECK (idempotency_key <> '' AND idempotency_key = btrim(idempotency_key)),
    request_hash VARCHAR(64) NOT NULL CHECK (request_hash ~ '^[a-f0-9]{64}$'),
    hash_version INTEGER NOT NULL CHECK (hash_version > 0),
    input_conversation_id BIGINT CHECK (input_conversation_id IS NULL OR input_conversation_id > 0),
    window_id UUID NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'RESERVED' CHECK (state IN ('RESERVED', 'RECONCILING', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
    execution_fence BIGINT NOT NULL CHECK (execution_fence > 0),
    lease_owner UUID NOT NULL,
    lease_expires_at TIMESTAMPTZ NOT NULL,
    admitted_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    failure_code VARCHAR(64),
    CONSTRAINT ck_ai_turn_dates CHECK (lease_expires_at > admitted_at
        AND (completed_at IS NULL OR completed_at >= admitted_at)),
    CONSTRAINT ck_ai_turn_completion CHECK ((state IN ('RESERVED', 'RECONCILING')) = (completed_at IS NULL)),
    CONSTRAINT ck_ai_turn_failure CHECK (
        (state IN ('FAILED', 'CANCELLED') AND failure_code IS NOT NULL AND btrim(failure_code) <> '')
        OR (state NOT IN ('FAILED', 'CANCELLED') AND failure_code IS NULL)),
    CONSTRAINT fk_ai_turn_window FOREIGN KEY (window_id, user_id) REFERENCES ai_quota_windows(id, user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_ai_turn_key UNIQUE (user_id, operation, idempotency_key)
);
CREATE INDEX idx_ai_turn_owner ON ai_turn_usages(user_id, admitted_at DESC, id);
CREATE INDEX idx_ai_turn_recovery ON ai_turn_usages(lease_expires_at, id) WHERE state IN ('RESERVED', 'RECONCILING');
CREATE INDEX idx_ai_turn_window ON ai_turn_usages(window_id);
CREATE INDEX idx_ai_turn_shop ON ai_turn_usages(shop_id);

-- Immutable financial evidence; a future manual-resolution feature needs a separate reviewed record.
-- Schema owners can bypass triggers; production application and migration roles must be separate.
CREATE FUNCTION billing_reject_evidence_mutation() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Billing evidence is append-only' USING ERRCODE = '55000';
END;
$$;
CREATE TRIGGER trg_billing_bank_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON billing_bank_transactions
    FOR EACH STATEMENT EXECUTE FUNCTION billing_reject_evidence_mutation();
CREATE TRIGGER trg_billing_grants_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON billing_subscription_grants
    FOR EACH STATEMENT EXECUTE FUNCTION billing_reject_evidence_mutation();

-- No policies/client grants. Application role provisioning belongs to the private rollout procedure.
ALTER TABLE billing_payment_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE billing_bank_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE billing_subscription_periods ENABLE ROW LEVEL SECURITY;
ALTER TABLE billing_subscription_grants ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_quota_windows ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_turn_usages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON billing_payment_requests, billing_bank_transactions, billing_subscription_periods,
    billing_subscription_grants, ai_quota_windows, ai_turn_usages FROM PUBLIC;
REVOKE ALL ON FUNCTION billing_reject_evidence_mutation() FROM PUBLIC;
DO $$
DECLARE table_name TEXT; role_name TEXT; sequence_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['billing_payment_requests', 'billing_bank_transactions',
        'billing_subscription_periods', 'billing_subscription_grants', 'ai_quota_windows', 'ai_turn_usages'] LOOP
        sequence_name := pg_get_serial_sequence(format('%I.%I', current_schema(), table_name), 'id');
        IF sequence_name IS NOT NULL THEN EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC', sequence_name); END IF;
        FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated', 'ai_sql_reader'] LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
                EXECUTE format('REVOKE ALL ON TABLE %I.%I FROM %I', current_schema(), table_name, role_name);
                IF sequence_name IS NOT NULL THEN
                    EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM %I', sequence_name, role_name);
                END IF;
            END IF;
        END LOOP;
    END LOOP;
END $$;
