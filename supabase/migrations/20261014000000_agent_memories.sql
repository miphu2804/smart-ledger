-- Agent long-term memory (ADR-0002), modelled on Tencent's `memory.records`
-- (https://www.tencentcloud.com/document/product/409/80363): append-only facts with a
-- cosine HNSW index, a memory type, an importance score, free-form metadata and an
-- optional expiry. Changes from Tencent's table, to match this repo:
--   * shop_id/user_id BIGINT with foreign keys replace tenant_id/agent_id UUID, and the
--     AI service filters both in every statement, as it does for chat_conversations.
--     Tencent's `app.tenant_id` policy would not apply anyway: the service connects as
--     a role that bypasses row-level security.
--   * source_conversation_id cascades, so deleting a chat also forgets what it taught.
--   * vector(384) fits paraphrase-multilingual-MiniLM-L12-v2; another embedding model
--     with another size needs a new migration that re-embeds every row.
-- Apply after the AI baseline, which creates the vector extension and chat_conversations.

CREATE TABLE IF NOT EXISTS agent_memories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL REFERENCES shops (id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    source_conversation_id BIGINT NOT NULL
        REFERENCES chat_conversations (id) ON DELETE CASCADE,
    memory_type VARCHAR(16) NOT NULL
        CHECK (memory_type IN ('preference', 'semantic', 'procedural', 'episodic')),
    content TEXT NOT NULL,
    embedding vector(384) NOT NULL,
    importance DOUBLE PRECISION NOT NULL DEFAULT 0.5
        CHECK (importance BETWEEN 0 AND 1),
    metadata JSONB NOT NULL DEFAULT '{}',
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_agent_memories_shop_user
    ON agent_memories (shop_id, user_id);

CREATE INDEX IF NOT EXISTS idx_agent_memories_source_conversation
    ON agent_memories (source_conversation_id);

CREATE INDEX IF NOT EXISTS idx_agent_memories_embedding
    ON agent_memories USING hnsw (embedding vector_cosine_ops);

-- Row-level security with no policy: Supabase's API roles (anon, authenticated) see no
-- rows, while the AI service's role, which owns or bypasses it, keeps full access.
ALTER TABLE agent_memories ENABLE ROW LEVEL SECURITY;
